#!/usr/bin/env python3
"""Render the model catalogue from the per-model `model.toml` files.

    python tools/build_feature_matrix.py            # write docs/feature-matrix.{md,csv}
    python tools/build_feature_matrix.py --stdout    # print, write nothing

The declared matrix produced here is one half of the pair; the other half is the
measured function divergence from `tools/variant_check.py`. Read them together:
a difference in one and not the other is either an undeclared feature or an
unpropagated change.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # py<3.11
    import tomli as tomllib  # type: ignore

COLUMNS = ["name", "family", "fields", "dimensionality", "discretization",
           "boundaries", "backend", "precision", "stepper", "order",
           "external_V", "status", "migrated"]


def load(models_dir: Path) -> list[dict]:
    rows = []
    for toml_path in sorted(models_dir.glob("*/model.toml")):
        with toml_path.open("rb") as fh:
            doc = tomllib.load(fh)
        model = dict(doc.get("model", {}))
        model["migrated"] = doc.get("provenance", {}).get("migrated", False)
        model["papers"] = ", ".join(doc.get("usage", {}).get("papers", [])) or "—"
        model["source"] = doc.get("provenance", {}).get("source", "")
        if isinstance(model.get("fields"), list):
            model["fields"] = "+".join(model["fields"])
        rows.append(model)
    return rows


def fmt(value) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    return "—" if value is None else str(value)


def markdown(rows: list[dict]) -> str:
    head = "| " + " | ".join(COLUMNS) + " |"
    rule = "|" + "|".join("---" for _ in COLUMNS) + "|"
    body = ["| " + " | ".join(fmt(r.get(c)) for c in COLUMNS) + " |" for r in rows]
    counts = {}
    for r in rows:
        counts[r.get("family", "?")] = counts.get(r.get("family", "?"), 0) + 1
    summary = ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))
    return "\n".join([
        "# Feature matrix (declared)",
        "",
        "Generated by `tools/build_feature_matrix.py` — do not edit.",
        "",
        f"{len(rows)} models ({summary}).",
        "",
        head, rule, *body,
        "",
        "## Measured divergence",
        "",
        "Run `python tools/variant_check.py --root src/pfc_models scan` for the",
        "function-level comparison across `models/*/simulation.py` and across",
        "sibling substrate modules. A function that differs between two models",
        "whose declared features are identical is an unpropagated change.",
        "",
    ])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="src/pfc_models/models")
    ap.add_argument("--docs", default="docs")
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args(argv)

    models_dir = Path(args.models)
    if not models_dir.is_dir():
        print(f"no such directory: {models_dir}", file=sys.stderr)
        return 2
    rows = load(models_dir)
    if not rows:
        print(f"no model.toml files under {models_dir}", file=sys.stderr)
        return 2

    text = markdown(rows)
    if args.stdout:
        print(text)
        return 0

    docs = Path(args.docs)
    docs.mkdir(parents=True, exist_ok=True)
    (docs / "feature-matrix.md").write_text(text, encoding="utf-8")
    with (docs / "feature-matrix.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS + ["papers", "source"],
                                extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({k: fmt(row.get(k)) for k in writer.fieldnames})
    print(f"wrote {docs/'feature-matrix.md'} and {docs/'feature-matrix.csv'} "
          f"({len(rows)} models)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
